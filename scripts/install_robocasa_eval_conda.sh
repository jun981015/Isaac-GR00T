#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="${REPO_DIR:-/home/junhyeong/Value/Isaac-GR00T}"
ROBOCASA_DIR="${ROBOCASA_DIR:-/home/junhyeong/workspace/robocasa}"
ROBOSUITE_DIR="${ROBOSUITE_DIR:-/home/junhyeong/workspace/robosuite}"
ENV_NAME="${ENV_NAME:-robocasa-eval}"

if ! command -v conda >/dev/null 2>&1; then
  echo "conda not found. Activate conda or source conda.sh first." >&2
  exit 1
fi

for path in "${REPO_DIR}" "${ROBOCASA_DIR}" "${ROBOSUITE_DIR}"; do
  if [[ ! -d "${path}" ]]; then
    echo "missing directory: ${path}" >&2
    exit 1
  fi
done

conda env create -n "${ENV_NAME}" -f "${REPO_DIR}/envs/robocasa-eval-environment.yml" || \
  conda env update -n "${ENV_NAME}" -f "${REPO_DIR}/envs/robocasa-eval-environment.yml" --prune

conda run -n "${ENV_NAME}" python -m pip install -r "${REPO_DIR}/envs/robocasa-eval-requirements.txt"
conda run -n "${ENV_NAME}" python -m pip install --no-deps --force-reinstall "${ROBOSUITE_DIR}"
conda run -n "${ENV_NAME}" python -m pip install --no-deps -e "${ROBOCASA_DIR}"

conda run -n "${ENV_NAME}" python -c "
from pathlib import Path
import site
for site_dir in site.getsitepackages():
    macros = Path(site_dir) / 'robosuite' / 'macros.py'
    if macros.exists():
        private = macros.with_name('macros_private.py')
        private.write_text(
            '# Generated by scripts/install_robocasa_eval_conda.sh\n'
            '# Numba cache can fail for this RoboSuite package layout.\n'
            'CACHE_NUMBA = False\n'
        )
        print(f'wrote {private}')
        break
else:
    raise SystemExit('could not locate installed robosuite/macros.py')
"

cd "${REPO_DIR}"
PYTHONPATH="${REPO_DIR}:${ROBOCASA_DIR}:${PYTHONPATH:-}" conda run -n "${ENV_NAME}" python -c "
import imageio
import mujoco
import numpy as np
import pandas
import robocasa
import robosuite
import zmq
from gr00t.eval.robot import RobotInferenceClient
print('robocasa-eval import smoke ok')
print('mujoco', mujoco.__version__)
print('numpy', np.__version__)
print('robocasa', getattr(robocasa, '__version__', 'unknown'))
print('robosuite', getattr(robosuite, '__version__', 'unknown'))
print('client', RobotInferenceClient.__name__)
"

cat <<EOF
Installed conda env: ${ENV_NAME}

Default runtime exports:
  export MUJOCO_GL=egl
  export PYOPENGL_PLATFORM=egl
  export OMP_NUM_THREADS=1
  export MKL_NUM_THREADS=1
  export OPENBLAS_NUM_THREADS=1
  export NUMEXPR_NUM_THREADS=1

Run eval with:
  ENV_NAME=PnPCounterToSink N_EPISODES=1 N_ENVS=1 bash scripts/run_robocasa_n15_zmq_parallel_eval_conda.sh
EOF
